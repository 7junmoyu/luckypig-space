// Execute with ego-browser nodejs; this checks explicitly labelled local samples.
const task = await taskSpace('luckypig-halo-integration');
const page = task.page('p1');
await page.goto('http://127.0.0.1:4173/#project/comfy-workflow');
await page.reload();
await page.waitForFunction(() => document.querySelector('video')?.readyState >= 2, undefined, { timeout: 10000 });
const metadata = await page.evaluate(() => ({ duration: document.querySelector('video').duration, source: document.querySelector('video').currentSrc }));
if (Math.abs(metadata.duration - 3) > .15 || !metadata.source.includes('/demo-media/')) throw new Error('Local test video was not loaded');
await page.evaluate(() => { document.querySelector('video').currentTime = 1.4; });
await page.waitForFunction(() => { const video = document.querySelector('video'); return !video.seeking && Math.abs(video.currentTime - 1.4) < .1; }, undefined, { timeout: 5000 });
await page.evaluate(async () => { const video = document.querySelector('video'); video.muted = true; await video.play(); });
await page.waitForFunction(() => document.querySelector('video').currentTime > 1.7, undefined, { timeout: 5000 });
await page.evaluate(() => document.querySelector('video').pause());
console.log({ localVideoMetadataSeekPlayPause: 'passed', duration: metadata.duration });
await page.click('loc=css:.image-preview-button');
await page.waitForFunction(() => document.querySelector('#image-dialog').open && document.querySelector('#image-preview').naturalWidth > 0, undefined, { timeout: 5000 });
await page.keyboard.press('Escape');
if (!await page.evaluate(() => document.querySelector('#project-dialog').open && !document.querySelector('#image-dialog').open)) throw new Error('Closing image did not return to work');
console.log({ imageZoomAndReturn: 'passed' });
const downloadPromise = page.waitForEvent('download', { timeout: 45000 });
await page.click('loc=css:a[download="notes.md"]');
const download = await downloadPromise;
await download.saveAs('/private/tmp/luckypig-downloaded-notes.md');
const { readFile } = await import('node:fs/promises');
const original = await readFile(new URL('../fixtures/upload-samples/notes.md', import.meta.url), 'utf8');
if (await readFile('/private/tmp/luckypig-downloaded-notes.md', 'utf8') !== original) throw new Error('Downloaded document differs from uploaded sample');
console.log({ actualDocumentDownload: 'passed', filename: download.suggestedFilename() });
await page.click('loc=css:button[data-copy-project="comfy-workflow"]');
await page.waitForFunction(() => document.querySelector('#toast').textContent === '作品链接已复制', undefined, { timeout: 3000 });
console.log({ shareLinkCopy: 'passed' });
console.log(await page.snapshot());
