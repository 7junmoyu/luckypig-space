const task = await taskSpace('luckypig-halo-integration');
const page = task.page('p1');
await page.goto('http://127.0.0.1:4173/?category=devops&tag=Kubernetes#projects');
await page.reload();
await page.waitForFunction(() => document.documentElement.dataset.ready === 'true', undefined, { timeout: 10000 });
await page.click('loc=css:button[data-project="gitops-delivery"]');
await page.waitForFunction(() => document.querySelector('#project-dialog').open && !!document.querySelector('#project-detail h2'), undefined, { timeout: 10000 });
if (!await page.evaluate(() => new URL(location.href).searchParams.get('tag') === 'Kubernetes')) throw new Error('Opening detail lost filters');
await page.evaluate(() => history.back());
await page.waitForFunction(() => !document.querySelector('#project-dialog').open && location.hash === '#projects', undefined, { timeout: 10000 });
if (await page.evaluate(() => document.querySelectorAll('.project-card').length) !== 1) throw new Error('Back lost filters');
await page.click('#clear-filters');
await page.waitForFunction(() => document.querySelectorAll('.project-card').length === 4, undefined, { timeout: 5000 });
await page.selectOption('#tag-filter', 'RAG');
await page.reload();
await page.waitForFunction(() => document.documentElement.dataset.ready === 'true', undefined, { timeout: 10000 });
if (!await page.evaluate(() => document.querySelector('#tag-filter').value === 'RAG' && document.querySelectorAll('.project-card').length === 1)) throw new Error('Reload lost tag');
console.log({ filtersBackClearReload: 'passed' });
const resourceCount = await page.evaluate(() => {
  window.__qaCard = document.querySelector('.project-card');
  const count = performance.getEntriesByType('resource').filter((r) => r.name.includes('/api/projects?')).length;
  document.dispatchEvent(new Event('visibilitychange'));
  return count;
});
await page.waitForFunction((count) => performance.getEntriesByType('resource').filter((r) => r.name.includes('/api/projects?')).length > count, resourceCount, { timeout: 10000 });
if (!await page.evaluate(() => window.__qaCard.isConnected && window.__qaCard === document.querySelector('.project-card'))) throw new Error('Unchanged refresh replaced interactive card');
console.log({ unchangedRefreshPreservesDom: 'passed' });
await page.cdp('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true });
const widths = await page.evaluate(() => ({ viewport: innerWidth, content: document.documentElement.scrollWidth }));
if (widths.viewport !== 390 || widths.content > 390) throw new Error('Mobile controls overflow');
console.log({ mobileWidth: widths });
await page.cdp('Emulation.clearDeviceMetricsOverride');
