import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawn } from 'node:child_process';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const assets = [
  { key: 'texture', path: 'creative-texture.jpg', url: 'https://images.unsplash.com/photo-1663335468790-cf7e8a1e0e73?auto=format&fit=crop&w=1100&q=80' },
  { key: 'argo', path: 'argo-cd-ui.gif', url: 'https://argoproj.github.io/argo-cd-ui.gif' },
  { key: 'video', path: 'ai-reference.mp4', url: 'https://videos.pexels.com/video-files/8084494/8084494-uhd_3840_2160_25fps.mp4' }
];
await mkdir(resolve(root, 'public/assets'), { recursive: true });
const results = [];
for (const asset of assets) {
  console.log(`Downloading ${asset.key} from ${new URL(asset.url).hostname}…`);
  const destination = resolve(root, 'public/assets', asset.path);
  const args = ['--fail', '--location', '--silent', '--show-error', '--max-time', '90', '--connect-timeout', '12', '--retry', '1', asset.url, '--output', destination];
  const success = await new Promise((resolveResult) => { const child = spawn('curl', args, { stdio: 'inherit' }); child.on('error', () => resolveResult(false)); child.on('close', (code) => resolveResult(code === 0)); });
  let valid = false;
  if (success) {
    const bytes = await readFile(destination);
    valid = bytes.length > 100 && (asset.key === 'texture' ? bytes[0] === 255 && bytes[1] === 216 : asset.key === 'argo' ? bytes.subarray(0, 3).toString() === 'GIF' : bytes.subarray(4, 8).toString() === 'ftyp');
  }
  results.push({ ...asset, success: success && valid });
  console.log(valid ? `Saved: public/assets/${asset.path}` : `Unavailable: ${asset.key}; keeping the original source link.`);
}
const mapping = Object.fromEntries(results.map((asset) => [asset.key, asset.success ? `./assets/${asset.path}` : asset.url]));
await writeFile(resolve(root, 'public/assets/media.js'), `// Generated by scripts/download-assets.mjs\nexport const media = ${JSON.stringify(mapping, null, 2)};\n`);
await writeFile(resolve(root, 'public/assets/download-status.json'), JSON.stringify({ checkedAt: new Date().toISOString(), downloaded: results.filter((r) => r.success).map((r) => r.path), references: results, status: results.every((r) => r.success) ? 'Downloaded and validated' : 'Some media remains remote' }, null, 2));
if (results.some((r) => !r.success)) process.exitCode = 1;
